const { chromium } = require('playwright');
const route = require('./route160.js');
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.route('**/*', route);
  await p.goto('http://localhost:8099/', { waitUntil: 'domcontentloaded', timeout: 90000 });
  await p.waitForFunction(() => window.THREE && THREE.REVISION);
  await p.evaluate(() => { msbApplyConfig({ pack: 25, asistentes: 100, extras: [{ id: 58, cantidad: 2 }] }); openQuoterWithPack(25); });
  await p.waitForTimeout(1500);
  const ok = (n, c) => console.log((c ? 'PASS ' : 'FAIL ') + n);
  ok('público: cuerpo marcado is-public', await p.evaluate(() => document.body.classList.contains('is-public')));
  ok('público: bloque de cuenta visible', await p.isVisible('#acceso-box'));
  ok('público: exportación HQ oculta', !(await p.isVisible('#hq-btn')));
  ok('público: dossier oculto', !(await p.isVisible('#dossier-btn')));
  ok('público: marca de agua forzada', await p.isChecked('#export-mark') && await p.isDisabled('#export-mark'));
  ok('público: planilla oculta', !(await p.isVisible('#plan-box')));
  ok('público: la vista 3D sigue disponible', await p.isVisible('#canvas-3d'));
  await p.fill('#registro-form input[name="nombre"]', 'Laura Prueba');
  await p.fill('#registro-form input[name="email"]', 'laura.nueva.' + Date.now() + '@example.com');
  await p.fill('#registro-form input[name="telefono"]', '612345678');
  await p.selectOption('#registro-form select[name="tipo"]', 'boda');
  await p.check('#registro-form input[name="privacidad"]');
  await p.click('#registro-form button[type="submit"]');
  await p.waitForTimeout(3000);
  const msg = await p.textContent('#registro-form .msg');
  console.log('mensaje registro:', msg);
  ok('registro autónomo confirma el envío', /Revisa tu correo|Ya tienes cuenta/.test(msg));
  require('fs').writeFileSync('reg_email.txt', 'ok');
  ok('sin errores de página', errs.filter(e => !/ERR_FAILED|Failed to load/.test(e)).length === 0);
  if (errs.length) console.log(errs.join(' | '));
  await b.close();
})().catch(e => { console.error('ERR', e.message); process.exit(1); });
